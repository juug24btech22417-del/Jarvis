// The overlay's live context brain — pure logic, no React, no network.
//
// WHY
// ---
// The old overlay sent one question plus the single previous exchange, so a
// follow-up ("what about the second option?") had nothing to attach to, and
// every sentence that looked like a question was treated as a brand new topic.
// This module is the bookkeeping that fixes that:
//
//   • parse the metadata line the model appends, WHILE it is still streaming
//   • keep a rolling window (recent turns) + a compact summary + durable facts
//   • notice when the subject actually changes, and mark what came before stale
//
// Everything here is a pure function so it can be unit-tested without a
// browser, a model or a call.

import { META_SENTINEL } from "./modes";

export interface Meta {
  confidence?: "high" | "medium" | "low";
  why?: string;
  missing?: string[];
  facts?: string[];
  topic?: string;
}

export type TurnRole = "them" | "you" | "assistant";

export interface Turn {
  id: string;
  role: TurnRole;
  text: string;
  at: number;
  /** Which capture produced it, or "typed" for the ask box. */
  via?: "system" | "mic" | "typed";
}

export interface Exchange {
  id: string;
  question: string;
  answer: string;
  mode: string;
  density: string;
  style: string;
  at: number;
  topic?: string;
  confidence?: Meta["confidence"];
  missing?: string[];
  /** True once the conversation moved on — the answer is kept but dimmed, so
   * the newest answer is always the one in the reading position. */
  stale?: boolean;
  /** Why it is stale, shown on the collapsed row ("topic changed"). */
  staleReason?: string;
  /** The stream was interrupted (newer question, or an error) — the text shown
   * is everything that arrived. */
  partial?: boolean;
  /** True when this answer is a "go deeper" expansion of the previous one. */
  expanded?: boolean;
  /** Regenerated by REPEAT — shown but flagged so it is not mistaken for a
   * second opinion. */
  repeated?: boolean;
}

/** Extract the first complete JSON object from a string (brace matching, so a
 * half-arrived metadata line while streaming simply yields null). */
export function firstJsonObject(raw: string): string | null {
  const start = raw.indexOf("{");
  if (start === -1) return null;
  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let i = start; i < raw.length; i++) {
    const c = raw[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (c === "\\") escaped = true;
      else if (c === '"') inString = false;
      continue;
    }
    if (c === '"') inString = true;
    else if (c === "{") depth++;
    else if (c === "}") {
      depth--;
      if (depth === 0) return raw.slice(start, i + 1);
    }
  }
  return null;
}

function asStringArray(v: unknown, max: number): string[] {
  if (!Array.isArray(v)) return [];
  return v
    .filter((x): x is string => typeof x === "string")
    .map((s) => s.trim())
    .filter((s) => s.length > 1 && s.length < 200)
    .slice(0, max);
}

/** Parse the metadata tail. Tolerates a partial or malformed payload. */
export function parseMeta(raw: string): Meta | null {
  const json = firstJsonObject(raw);
  if (!json) return null;
  let obj: Record<string, unknown>;
  try {
    obj = JSON.parse(json) as Record<string, unknown>;
  } catch {
    return null;
  }
  const confidence =
    obj.confidence === "high" || obj.confidence === "medium" || obj.confidence === "low"
      ? (obj.confidence as Meta["confidence"])
      : undefined;
  return {
    confidence,
    why: typeof obj.why === "string" ? obj.why.slice(0, 80) : undefined,
    missing: asStringArray(obj.missing, 4),
    facts: asStringArray(obj.facts, 3),
    topic: typeof obj.topic === "string" ? obj.topic.trim().slice(0, 60) : undefined,
  };
}

/**
 * Split a (possibly still-streaming) answer into what the user may read and the
 * metadata.
 *
 * While streaming, the sentinel arrives one token at a time, so any trailing
 * PREFIX of it is held back — that is what stops `<<<JARVIS_M` flashing into
 * the answer for a frame. `streaming: false` (the finished answer) skips that
 * hold-back, because a real answer is allowed to end with "<".
 */
export function splitStreamingAnswer(
  raw: string,
  streaming = true
): { body: string; meta: Meta | null; complete: boolean } {
  const i = raw.indexOf(META_SENTINEL);
  if (i >= 0) {
    const body = raw.slice(0, i).replace(/\s+$/, "");
    const tail = raw.slice(i + META_SENTINEL.length);
    const complete = /\}\s*>>>/.test(tail) || /\}\s*$/.test(tail.trim()) || />>>/.test(tail);
    return { body, meta: parseMeta(tail), complete };
  }
  if (streaming) {
    for (let k = META_SENTINEL.length - 1; k >= 1; k--) {
      if (raw.endsWith(META_SENTINEL.slice(0, k))) {
        return { body: raw.slice(0, raw.length - k).replace(/\s+$/, ""), meta: null, complete: false };
      }
    }
  }
  return { body: raw, meta: null, complete: false };
}

const STOPWORDS = new Set([
  "the", "a", "an", "and", "or", "but", "if", "of", "to", "in", "on", "for", "with", "is", "are", "was",
  "were", "be", "been", "do", "does", "did", "can", "could", "would", "should", "will", "that", "this",
  "these", "those", "it", "its", "as", "at", "by", "from", "so", "then", "than", "too", "very", "you",
  "your", "we", "our", "they", "their", "i", "me", "my", "he", "she", "them", "what", "how", "why",
  "when", "where", "who", "which", "about", "into", "there", "here", "just", "like", "get", "got",
]);

export function tokens(text: string): string[] {
  return (text || "")
    .toLowerCase()
    .replace(/[^a-z0-9+#./\s-]/g, " ")
    .split(/\s+/)
    .map((t) => t.replace(/^[-./]+|[-./]+$/g, ""))
    .filter((t) => t.length > 2 && !STOPWORDS.has(t));
}

/**
 * Two content words are the same word when one is a prefix of the other and the
 * shared stem is long enough to be meaningful — "postgres/postgresql",
 * "token/tokens", "authenticate/authentication". Without this, morphological
 * variants read as brand new vocabulary and every second sentence looks like a
 * topic change.
 */
function sameWord(a: string, b: string): boolean {
  if (a === b) return true;
  const [short, long] = a.length <= b.length ? [a, b] : [b, a];
  return short.length >= 4 && long.startsWith(short);
}

/** Jaccard overlap of content words — cheap, language-agnostic topic proxy. */
export function similarity(a: string, b: string): number {
  const A = [...new Set(tokens(a))];
  const B = [...new Set(tokens(b))];
  if (!A.length || !B.length) return 0;
  let shared = 0;
  for (const t of A) if (B.some((u) => sameWord(t, u))) shared++;
  const union = A.length + B.length - shared;
  return union > 0 ? shared / union : 0;
}

/**
 * Has the subject changed? A new topic is a *sustained* change: one short
 * follow-up worded with new vocabulary ("and the deadline?") stays on topic.
 *
 * `threshold` is deliberately low-ish (0.18): in a real call about the same
 * subject, consecutive sentences share fewer words than they look like they do.
 */
export function detectTopicShift(previousTopic: string, next: string, threshold = 0.18): boolean {
  if (!previousTopic.trim()) return true;
  const nextText = next.trim();
  if (nextText.length < 12) return false;
  return similarity(previousTopic, nextText) < threshold;
}

/** The topic label to carry forward: the model's label when it gave one, else
 * the words of the question itself. */
export function nextTopicLabel(previousTopic: string, question: string, metaTopic?: string): string {
  if (metaTopic && metaTopic.trim().length > 2) return metaTopic.trim();
  if (!previousTopic.trim()) return question.slice(0, 80);
  return detectTopicShift(previousTopic, question) ? question.slice(0, 80) : previousTopic;
}

/**
 * Merge newly-learned facts into the durable list.
 *
 * Dedupe is fuzzy on purpose: the model re-states the same fact with different
 * wording every few turns ("budget is 40k" / "their budget is 40 thousand"), so
 * an exact-match set would grow without bound and push the real context out of
 * the prompt.
 */
export function mergeFacts(existing: string[], incoming: string[] | undefined, max = 12): string[] {
  const out = [...existing];
  for (const raw of incoming || []) {
    const fact = raw.trim();
    if (fact.length < 3) continue;
    const dup = out.some((f) => f.toLowerCase() === fact.toLowerCase() || similarity(f, fact) > 0.6);
    if (!dup) out.push(fact);
  }
  // Keep the newest, they are the most likely to matter in the next minute.
  return out.slice(-max);
}

/** Facts may also arrive as "the same thing with new detail" — replace a fact
 * when the new one is a strict superset of it, so numbers get updated instead
 * of duplicated. */
export function updateFacts(existing: string[], incoming: string[] | undefined, max = 12): string[] {
  const out = [...existing];
  for (const raw of incoming || []) {
    const fact = raw.trim();
    if (fact.length < 3) continue;
    const supersedes = out.findIndex((f) => {
      const a = f.toLowerCase();
      const b = fact.toLowerCase();
      return a !== b && (b.includes(a) || a.includes(b)) && similarity(a, b) > 0.35;
    });
    if (supersedes >= 0) {
      // Same subject, newer wording: the longer text usually carries the update.
      if (fact.length >= out[supersedes].length) out[supersedes] = fact;
      continue;
    }
    const dup = out.some((f) => f.toLowerCase() === fact.toLowerCase() || similarity(f, fact) > 0.6);
    if (!dup) out.push(fact);
  }
  return out.slice(-max);
}

/**
 * The turns worth sending: the most recent ones, capped by count and size.
 * Everything older is represented by `summary` instead — that is what keeps a
 * two-hour call from sending a two-hour transcript on every question.
 */
export function rollingWindow(turns: Turn[], maxTurns = 10, maxChars = 2600): Turn[] {
  const out: Turn[] = [];
  let chars = 0;
  for (let i = turns.length - 1; i >= 0; i--) {
    const t = turns[i];
    const text = t.text.trim();
    if (!text) continue;
    if (out.length >= maxTurns) break;
    if (chars + text.length > maxChars && out.length > 0) break;
    chars += text.length;
    out.push({ ...t, text });
  }
  return out.reverse();
}

/** How many turns have scrolled past the window — the trigger for a background
 * compaction pass. */
export function turnsToCompact(turns: Turn[], windowSize = 10): number {
  return Math.max(0, turns.length - windowSize);
}

/**
 * Mark everything but the newest answer stale. Stale answers are kept (they are
 * often what the other person is still talking about) but they move out of the
 * reading position and stop being the thing a follow-up refers to.
 */
export function markStale(exchanges: Exchange[], keepId: string): Exchange[] {
  return exchanges.map((e) => (e.id === keepId ? { ...e, stale: false } : { ...e, stale: true }));
}

/** Which answer the model should treat as "your previous answer". */
export function currentExchange(exchanges: Exchange[]): Exchange | null {
  return exchanges.find((e) => !e.stale) || exchanges[0] || null;
}

/** Flat text of the conversation so far, for the summariser. */
export function transcriptText(turns: Turn[], limit = 6000): string {
  const lines = turns.map((t) => `${t.role === "them" ? "OTHER" : "USER"}: ${t.text}`);
  const joined = lines.join("\n");
  return joined.length > limit ? joined.slice(-limit) : joined;
}

let seq = 0;
/** Stable ids without pulling a uuid dependency into the render path. */
export function uid(prefix = "id"): string {
  seq = (seq + 1) % 1_000_000;
  return `${prefix}-${Date.now().toString(36)}-${seq.toString(36)}`;
}
